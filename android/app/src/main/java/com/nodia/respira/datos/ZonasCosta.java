    // --------------------------------------------------------------
    // # Las zonas no recibidas conservan su contorno real y muestran «Sin datos».
    // + lecturas: [Zona]
    //       -->
    //     conMediciones() --x
    //       <--
    //   [Zona]
    // --------------------------------------------------------------
    public static List<Zona> conMediciones(List<Zona> lecturas) {
        Map<String, Zona> porId = new HashMap<>();
        for (Zona lectura : lecturas) porId.put(lectura.id, lectura);
        List<Zona> resultado = new ArrayList<>();
        for (Zona catalogo : zonas()) {
            Zona lectura = porId.get(catalogo.id);
            resultado.add(lectura == null ? catalogo : fusionar(catalogo, lectura));
        }
        return resultado;
    }

    // --------------------------------------------------------------
    // + lat: R, lng: R
    //       -->
    //     enAmbito() --x
    //       <--
    //   B
    // --------------------------------------------------------------
    public static boolean enAmbito(double lat, double lng) {
        return Double.isFinite(lat) && Double.isFinite(lng)
                && lat >= 38.981 && lat <= 39.026 && lng >= -0.187 && lng <= -0.139;
    }

    // --------------------------------------------------------------
    // - catalogo: Zona, lectura: Zona
    //       -->
    //     fusionar() --x
    //       <--
    //   Zona
    // --------------------------------------------------------------
    private static Zona fusionar(Zona catalogo, Zona lectura) {
        Zona zona = new Zona(catalogo.id, catalogo.tipo, catalogo.nombre, catalogo.contorno,
                lectura.haceMin, lectura.numMediciones, null, null, null)
                .conNombreCorto(catalogo.nombreCorto()).conEtiquetaEn(catalogo.posicionEtiqueta())
                .conContornos(catalogo.contornos());
        for (Magnitud m : Magnitud.values()) {
            zona.conDato(m, lectura.dato(m)).conMedia24h(m, lectura.media24h(m));
        }
        return zona;
    }

    // --------------------------------------------------------------
    // - id: Text, tipo: Text, nombre: Text, etiqueta: Text, ancla: Punto, area: Area
    //       -->
    //     crear() --x
    //       <--
    //   Zona
    // --------------------------------------------------------------
    private static Zona crear(String id, String tipo, String nombre, String etiqueta,
                              double[] ancla, double[][][][] area) {
        List<List<List<double[]>>> poligonos = new ArrayList<>();
        for (double[][][] poligono : area) {
            List<List<double[]>> anillos = new ArrayList<>();
            for (double[][] anillo : poligono) {
                List<double[]> puntos = new ArrayList<>();
                for (double[] punto : anillo) puntos.add(punto);
                anillos.add(puntos);
            }
            poligonos.add(anillos);
        }
        return new Zona(id, tipo, nombre, poligonos.get(0).get(0), null, 0, null, null, null)
                .conNombreCorto(etiqueta).conEtiquetaEn(ancla).conContornos(poligonos);
    }
